// How often each superbiome appears in the universe (docs/UNIVERSO.md, phase 14). The map is not changed: this only
// counts, over several worlds, the regions of each superbiome and writes src/superbiome-rarity.js.
// Usage: node scripts/superbiome-census.mjs [radius=40] [--check]
import {writeFileSync,readFileSync} from 'node:fs';
import {FAMILIES,LAND_REGIONS,ABYSS_REGIONS,superbiome} from '../src/superbiomes.js';
import {newRegionOf} from '../src/universe-regions.js';
export const SEEDS=['','humedal-01','orilla-7','faro-3','nebulosa-9','marea-12'];
const storage=new Map();globalThis.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
export async function census(radius=40,seeds=SEEDS){
 const counts={};let land=0,abyss=0;
 for(const seed of seeds){
  globalThis.location={search:seed?`?testSeed=${seed}&layout=classic&generation=2`:''};
  const v='?census='+encodeURIComponent(seed),[d,p,w]=await Promise.all(['data','progress','world'].map(n=>import(new URL('../src/'+n+'.js'+v,import.meta.url))));
  const r={};d.initialize(r);p.initialize(r);w.initialize(r);r.S.todayKey='2026-10-22';const seen=new Set();
  for(let x=-radius;x<=radius;x++)for(let y=-radius;y<=radius;y++){const g=r.regionOfPos((x+.5)*r.WCH,(y+.5)*r.WCH);if(seen.has(g.key))continue;seen.add(g.key);
   const region=g.sea?newRegionOf(g.key,true)?.id||'vacio':r.BIOMES[g.z].id,sb=superbiome(region,g.genre);if(!sb)continue;counts[sb.id]=(counts[sb.id]||0)+1;if(g.sea)abyss++;else land++;}
 }
 return {counts,land,abyss};
}
// Rarity of a continent superbiome by its share of continent regions; the Abyss ones by their share of the Abyss.
export function rarity(count,total){const share=count/Math.max(1,total);return count===0?'ausente':share>=.005?'comun':share>=.0015?'raro':'muy-raro';}
export function table({counts,land,abyss}){const out={};
 for(const region of LAND_REGIONS)for(const f of FAMILIES)out[region+':'+f.id]=rarity(counts[region+':'+f.id]||0,land);
 for(const region of ABYSS_REGIONS)out[region+':ambient']=rarity(counts[region+':ambient']||0,abyss);return out;}
export function source(t,stats){return `// Generated by scripts/superbiome-census.mjs over ${SEEDS.length} worlds (${stats.land} continent and ${stats.abyss} Abyss regions).
// How often each superbiome appears in the universe; the map is not changed to fill the absent ones.
export const SUPERBIOME_RARITY=Object.freeze(${JSON.stringify(t)});
`;}
if(import.meta.url===`file://${process.argv[1]}`){
 const radius=Number(process.argv[2])||40,stats=await census(radius),t=table(stats),text=source(t,stats),file=new URL('../src/superbiome-rarity.js',import.meta.url);
 if(process.argv.includes('--check')){if(readFileSync(file,'utf8')!==text){console.error('FAIL superbiome-rarity.js is out of date');process.exit(1);}}else writeFileSync(file,text);
 const n=k=>Object.values(t).filter(v=>v===k).length;
 console.log(`PASS census of ${SEEDS.length} worlds: ${n('comun')} common, ${n('raro')} rare, ${n('muy-raro')} very rare, ${n('ausente')} absent`);
}
